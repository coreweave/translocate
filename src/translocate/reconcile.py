"""Cross-check the inventory against the live filesystem.

RECORD is a claim; the filesystem is the witness. For every entry
whose content is supposed to be on disk, this stage stats the file
and (when RECORD recorded a hash) re-hashes it; mismatches and
missing files get flagged on the entry for the downstream emitter or
materializer to decide what to do with.

Then a residue walk scans every directory the distribution owns.
Lazily-generated bytecode under ``__pycache__/`` is paired with a
recorded ``.py`` sibling and dropped (regenerable); everything else
becomes an ``unrecorded-residue`` entry on the inventory so a
downstream consumer can choose to report, include, or ignore it.

The stat + hash fan-out runs across the caller-provided thread pool.
"""

from __future__ import annotations

import os
import re
from concurrent.futures import Executor, ThreadPoolExecutor
from pathlib import Path, PurePosixPath
from typing import Dict, List, Optional, Set, Tuple

from translocate._hashing import hash_file_sha256
from translocate.inventory import (
    Category,
    ContentKind,
    ContentRef,
    Entry,
    EntryFlags,
    Inventory,
)
from translocate.scheme import classify

# PEP 3147 bytecode filenames take the form
# ``<modulename>.<cachetag>.pyc``, where the cache tag encodes the
# implementation and Python version (e.g. ``foo.cpython-310.pyc``).
# Extracting the stem is how a ``.pyc`` gets matched against its
# recorded ``.py`` source.
_PYC_NAME_RE = re.compile(r"^(?P<stem>[^.]+)(?:\..+)?\.pyc$")


def _stat_and_hash(
    entry: Entry,
) -> Tuple[Entry, Optional[os.stat_result], Optional[Tuple[str, int]]]:
    """Stat (and optionally hash) one entry's on-disk file.

    Workers run on a thread pool; the entry isn't mutated here.
    ``_apply_disk_observation`` folds the observation back on the
    main thread so all writes to ``Entry`` happen single-threaded.
    """
    if entry.content_ref.kind != ContentKind.ON_DISK:
        return entry, None, None
    path = entry.content_ref.on_disk_path
    if path is None:
        return entry, None, None
    try:
        st = os.stat(path)
    except FileNotFoundError:
        return entry, None, None
    digest: Optional[Tuple[str, int]] = None
    if entry.src_hash and entry.src_hash[1]:
        # Modern RECORDs spell hashes as sha256. A legacy algorithm
        # leaves ``disk_hash`` unset.
        if entry.src_hash[0] in ("sha256", ""):
            digest = hash_file_sha256(path)
    return entry, st, digest


def _apply_disk_observation(
    entry: Entry,
    st: Optional[os.stat_result],
    digest: Optional[Tuple[str, int]],
) -> None:
    if st is None:
        if entry.content_ref.kind == ContentKind.ON_DISK:
            entry.flags.missing_on_disk = True
        return
    entry.src_mode = st.st_mode
    if digest is not None:
        entry.disk_hash = ("sha256", digest[0])
        entry.disk_size = digest[1]
        if entry.src_hash and entry.src_hash[1] != digest[0]:
            entry.flags.hash_mismatch = True
    elif entry.src_size is None:
        entry.disk_size = st.st_size


def _dist_owned_dirs(entries: List[Entry], inventory: Inventory) -> Set[Path]:
    """Directories solely owned by this distribution.

    The dist-info directory, plus every first-segment ancestor under
    purelib or platlib that a nested RECORD entry enters (e.g.
    ``<purelib>/torch`` for an entry like ``torch/foo.py``).
    """
    owned: Set[Path] = {inventory.dist_info_dir}
    scheme = inventory.source_scheme
    for entry in entries:
        if entry.flags.outside_known_scheme:
            continue
        parts = entry.rel_path.parts
        if len(parts) < 2:
            continue
        first_segment = parts[0]
        # __pycache__ is CPython's shared bytecode cache for everything
        # under its parent directory, never a single package's tree.
        if first_segment == "__pycache__":
            continue
        if entry.category == Category.ROOT_PURELIB:
            owned.add(scheme.purelib / first_segment)
        elif entry.category == Category.ROOT_PLATLIB:
            owned.add(scheme.platlib / first_segment)
    return owned


def _recorded_directories(
    entries: List[Entry], owned_roots: Set[Path]
) -> Set[Path]:
    """Dist-owned directories that transitively contain a recorded file.

    Each walk runs from a recorded file's parent up to the owning
    root. Entries outside every owned root contribute nothing.
    """
    dirs: Set[Path] = set()
    for entry in entries:
        if entry.flags.outside_known_scheme:
            continue
        path = entry.content_ref.on_disk_path
        if path is None:
            continue
        relevant_root: Optional[Path] = None
        for root in owned_roots:
            try:
                path.relative_to(root)
                relevant_root = root
                break
            except ValueError:
                continue
        if relevant_root is None:
            continue
        parent = path.parent
        while True:
            if parent in dirs:
                break
            dirs.add(parent)
            if parent == relevant_root:
                break
            if parent == parent.parent:
                break
            parent = parent.parent
    return dirs


def _residue_walk(
    entries: List[Entry],
    inventory: Inventory,
) -> List[Entry]:
    """Scan dist-owned directories for files not listed in RECORD.

    Bytecode under ``__pycache__/`` paired by stem with a recorded
    ``.py`` sibling regenerates on demand; the walk drops it.
    Everything else becomes an ``unrecorded-residue`` entry for the
    back-ends to report.
    """
    recorded_paths: Set[Path] = set()
    py_files_by_dir: Dict[Path, Set[str]] = {}
    for entry in entries:
        path = entry.content_ref.on_disk_path
        if path is None:
            continue
        recorded_paths.add(path)
        if (
            entry.content_ref.kind == ContentKind.ON_DISK
            and path.suffix == ".py"
        ):
            py_files_by_dir.setdefault(path.parent, set()).add(path.stem)

    owned_roots = _dist_owned_dirs(entries, inventory)

    residue: List[Entry] = []
    seen: Set[Path] = set()
    for directory in _recorded_directories(entries, owned_roots):
        try:
            children = list(os.scandir(directory))
        except (FileNotFoundError, PermissionError):
            continue
        for child in children:
            child_path = Path(child.path)
            if child_path in recorded_paths or child_path in seen:
                continue
            if child.is_dir():
                continue
            seen.add(child_path)

            if (
                child_path.parent.name == "__pycache__"
                and child_path.suffix == ".pyc"
            ):
                m = _PYC_NAME_RE.match(child_path.name)
                if m:
                    source_dir = child_path.parent.parent
                    source_stem = m.group("stem")
                    if source_stem in py_files_by_dir.get(source_dir, set()):
                        continue
            residue.append(_build_residue_entry(child_path, inventory))
    return residue


def _build_residue_entry(path: Path, inventory: Inventory) -> Entry:
    category, rel = classify(
        path, inventory.source_scheme, inventory.root_is_purelib
    )
    flags = EntryFlags(is_unrecorded_residue=True)
    if category == Category.OUTSIDE_KNOWN_SCHEME:
        flags.outside_known_scheme = True
        rel = PurePosixPath(path.as_posix())
    try:
        st = os.stat(path)
        src_mode = st.st_mode
        src_size = st.st_size
    except OSError:
        src_mode = None
        src_size = None
    return Entry(
        category=category,
        rel_path=rel,
        content_ref=ContentRef.on_disk(path),
        src_hash=None,
        src_size=src_size,
        disk_size=src_size,
        src_mode=src_mode,
        flags=flags,
    )


def reconcile(
    inventory: Inventory, pool: Optional[Executor] = None
) -> Inventory:
    """Annotate ``inventory`` in place with disk state and residue entries.

    Each existing entry gains ``disk_hash``/``disk_size``/``src_mode``
    (or a ``missing_on_disk`` / ``hash_mismatch`` flag if the witness
    disagrees with the manifest). Files found in recorded directories
    that the manifest didn't list are appended as
    ``is_unrecorded_residue`` entries unless they pair with a
    recorded ``.py`` as regenerable bytecode.
    """
    owned_pool = pool is None
    pool = pool or ThreadPoolExecutor(
        max_workers=8, thread_name_prefix="translocate-io"
    )
    try:
        results = pool.map(_stat_and_hash, inventory.entries)
        for entry, st, digest in results:
            _apply_disk_observation(entry, st, digest)
    finally:
        if owned_pool:
            pool.shutdown(wait=True)
    inventory.entries.extend(_residue_walk(inventory.entries, inventory))
    return inventory
